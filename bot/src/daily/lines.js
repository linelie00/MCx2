/** 그 대목에서 한 줄(또는 한 벌)을 고른다. */
export function canned(character, key, rand = Math.random) {
  const pool = LINES[character]?.[key] ?? [];
  return pool.length ? pool[Math.floor(rand() * pool.length)] : null;
}

