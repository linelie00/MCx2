import { josa } from '../farm/requesters.js';

/** 조사 짝. 앞이 받침 있을 때, 뒤가 없을 때. */
const PAIRS = { 을: ['을', '를'], 를: ['을', '를'], 이: ['이', '가'], 가: ['이', '가'], 은: ['은', '는'], 는: ['은', '는'], 과: ['과', '와'], 와: ['과', '와'] };

/** 자리표시를 채운다. 모르는 자리는 그대로 둔다 — 검사가 잡는다. */
export function fill(template, vars = {}) {
  return String(template).replace(/\{(\w+)(?::(\S))?\}/g, (whole, key, particle) => {
    if (vars[key] == null) return whole;
    return particle && PAIRS[particle] ? josa(vars[key], PAIRS[particle]) : String(vars[key]);
  });
}

